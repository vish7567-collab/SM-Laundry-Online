-- SM Laundry empty Neon PostgreSQL schema (no customer/order/collection records)
-- Run once in the intended empty Neon database. Does not drop existing tables.
BEGIN;

CREATE TABLE collection (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id VARCHAR(50),
  phone VARCHAR(30) NOT NULL DEFAULT '',
  received_amount NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  received_date DATE NOT NULL,
  instrument_type VARCHAR(20) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source_key VARCHAR(80),
  CONSTRAINT uq_collection_source_key UNIQUE (source_key)
);
CREATE INDEX idx_collection_order ON collection(order_id);
CREATE INDEX idx_collection_received_date ON collection(received_date);


CREATE TABLE institutions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_name VARCHAR(255) NOT NULL UNIQUE,
  mobile_number VARCHAR(20) NOT NULL DEFAULT '',
  status VARCHAR(10) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Inactive')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE orders (
  id VARCHAR(50) PRIMARY KEY,
  "date" VARCHAR(20),
  "isoDate" VARCHAR(20),
  "time" VARCHAR(20),
  name VARCHAR(100),
  phone VARCHAR(20),
  "count" INTEGER,
  service VARCHAR(100),
  items TEXT,
  "extraCharge" NUMERIC(10,2) DEFAULT 0.00,
  collection NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  details TEXT,
  amount NUMERIC(10,2),
  status VARCHAR(20) DEFAULT 'Pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  received_amount NUMERIC(10,2),
  received_date DATE,
  instrument_type VARCHAR(20)
);


CREATE TABLE rates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_type VARCHAR(50) NOT NULL,
  item_name VARCHAR(100) NOT NULL,
  rate NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_rates_service_item UNIQUE (service_type, item_name)
);


CREATE TABLE service_rates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_type VARCHAR(50) NOT NULL,
  item_name VARCHAR(100) NOT NULL,
  rate NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_service_item UNIQUE (service_type, item_name)
);


COMMIT;
